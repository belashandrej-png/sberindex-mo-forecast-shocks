def online_cusum2(r, k=0.3, h_thr=2.5, init=6):
    if len(r) < init + 2: return []
    mu, sd = r[:init].mean(), r[:init].std() + 1e-9
    z = (r - mu) / sd
    sp = sn = 0.0; alarms = []
    for i, v in enumerate(z):
        sp = max(0.0, sp + v - k); sn = max(0.0, sn - v - k)
        if sp > h_thr or sn > h_thr:
            alarms.append(i); sp = sn = 0.0
    return alarms

