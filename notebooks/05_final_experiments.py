# 2. Корреляция между МО (временные ряды)
total = consumption[consumption['category'] == 'Все категории'].pivot_table(
    index='date', columns='territory_id', values='value')
top50 = total.sum().nlargest(50).index
corr_mo = total[top50].corr()
vals = corr_mo.values[np.triu_indices_from(corr_mo.values, k=1)]
print(f"Корреляция между рядами ТОП-50 МО: средняя={vals.mean():.3f}, "
      f"min={vals.min():.3f}, max={vals.max():.3f}")
print("Высокая средняя корреляция = общий национальный фактор (инфляция, праздники)")

# 3. Сеть: степень узлов и ближайший сосед
degree = pd.concat([connection['territory_id_x'].value_counts(),
                    connection['territory_id_y'].value_counts()]).groupby(level=0).sum()
min_dist = pd.concat([connection.groupby('territory_id_x')['distance'].min(),
                      connection.groupby('territory_id_y')['distance'].min()]).groupby(level=0).min()

net_features = pd.DataFrame({'degree': degree, 'min_dist': min_dist})
net_features = net_features.join(market_access.set_index('territory_id'))
net_features = net_features.join(total.sum().rename('total_spend'))
