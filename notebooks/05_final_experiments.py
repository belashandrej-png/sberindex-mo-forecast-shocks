def build_features(Y, nat, shares, net, sample_mos, cutoff):

    Y_sub = Y.iloc[:cutoff+1]
    nat_sub = nat.iloc[:cutoff+1]
    T = len(Y_sub)

    # Матрица признаков: строки = (t, mo), столбцы = признаки
    rows = []
    for t in range(1, T):
        for mo in sample_mos:
            y_t = Y_sub.iloc[t][mo]
            if pd.isna(y_t) or y_t == 0:
                continue
            feat = {'mo': mo, 't': t, 'y': np.log1p(y_t)}

            # 1. Лаги целевой переменной
            for lag in LAGS:
                if t - lag >= 0:
                    feat[f'y_lag{lag}'] = np.log1p(Y_sub.iloc[t-lag][mo])

            # 2. Скользящие статистики
            for w in [3, 6, 12]:
                if t >= w:
                    window = Y_sub.iloc[t-w:t][mo]
                    feat[f'y_roll_mean_{w}'] = np.log1p(window.mean())
                    feat[f'y_roll_std_{w}'] = window.std()

            # 3. YoY-приросты
            if t >= 12:
                y_now = Y_sub.iloc[t][mo]
                y_12 = Y_sub.iloc[t-12][mo]
                if y_12 > 0:
                    feat['yoy_12'] = y_now / y_12 - 1
                if t >= 13:
                    y_13 = Y_sub.iloc[t-13][mo]
                    if y_13 > 0:
                        feat['yoy_13'] = Y_sub.iloc[t-1][mo] / y_13 - 1

            # 4. Национальный индекс (с лагами) - общий макрофактор
            for lag in [0, 1, 3, 6, 12]:
                if t - lag >= 0:
                    feat[f'nat_lag{lag}'] = np.log1p(nat_sub.iloc[t-lag])
            if t >= 12:
                feat['nat_yoy'] = nat_sub.iloc[t] / nat_sub.iloc[t-12] - 1

            # 5. Доли категорий
            for sname, smat in shares.items():
                if t < len(smat) and mo in smat.columns:
                    v = smat.iloc[t][mo]
                    if not pd.isna(v):
                        feat[sname] = v

            # 6. Календарные признаки
            date_t = months[t]
            m = date_t.month
            feat['month_sin'] = np.sin(2 * np.pi * m / 12)
            feat['month_cos'] = np.cos(2 * np.pi * m / 12)
            feat['is_dec'] = int(m == 12)
            feat['is_jan'] = int(m == 1)

            # 7. Тренд
            feat['trend'] = t

            # 8. Сетевые/статические признаки
            feat['min_dist'] = net.loc[mo, 'min_dist'] if mo in net.index else 0
            feat['market_access'] = net.loc[mo, 'market_access'] if mo in net.index else 0

            rows.append(feat)

    df = pd.DataFrame(rows)
    return df

