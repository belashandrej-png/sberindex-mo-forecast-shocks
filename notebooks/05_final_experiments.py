def build_news_score(events, date_index, lead=1, decay=0.7):
    n = len(date_index)
    score = np.zeros(n)
    for _, ev in events.iterrows():
        onset_idx = np.where(date_index >= ev['date'])[0]
        if len(onset_idx) == 0:
            continue
        onset = onset_idx[0] + lead
        for d in range(4):
            i = onset + d
            if i < n:
                score[i] += ev['impact_strength'] * ev['impact_sign'] * np.exp(-decay * d)
    return score

def norm_ccf(x, y, max_lag=4):
    x = (x - x.mean()) / (x.std() + 1e-9)
    y = (y - y.mean()) / (y.std() + 1e-9)
    n = len(x)
    out = {}
    for k in range(-max_lag, max_lag + 1):
        a, b = (x[:n-k], y[k:]) if k >= 0 else (x[-k:], y[:n+k])
        out[k] = float(np.mean(a * b))
    return pd.Series(out)

