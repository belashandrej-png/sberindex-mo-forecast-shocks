def bic_pen(s):
    d = np.diff(s)
    v = d.var() if d.var() > 0 else 1e-6
    return max(np.log(len(s)) * v, 1e-6)

def cusum_cp(s, k=0.5, h=3.5):
    s = np.asarray(s, float)
    z = (s - s.mean()) / (s.std() + 1e-9)
    sp = sn = 0.0
    cps = []
    for i, v in enumerate(z):
        sp = max(0.0, sp + v - k)
        sn = max(0.0, sn - v - k)
        if sp > h or sn > h:
            cps.append(i)
            sp = sn = 0.0
    return cps

