def find_files(folder, extensions=['.csv', '.xlsx', '.parquet', '.json']):
    found = []
    for root, dirs, files in os.walk(folder):
        for file in files:
            if any(file.lower().endswith(ext) for ext in extensions):
                found.append(os.path.join(root, file))
    return found

